// Shared helpers for phase-2 art generators (node). Usage:
//   const L = require('./lib');
//   const art = {};                       // id -> svg string
//   art.trex = L.wrap('trex', innerSvg);  // innerSvg is authored on an 800x600 canvas
//   L.writeFile('trex-group', art);       // writes phase2/out/art2-trex-group.js
//
// wrap() does the boring contract work for you:
//   * puts the 800x600 drawing inside the site's  viewBox="0 0 400 300"  (scaled 0.5)
//   * prefixes EVERY id (gradients, clipPaths, filters...) and every reference to it with "<artId>-"
//     so pieces never collide when many SVGs are inlined in one page
//   * strips <g id="backdrop">...</g> (we want transparent backgrounds on the site)
//   * rejects <script>, on* handlers, external hrefs, width/height on the root
const fs = require('fs');
const path = require('path');

const f = n => Math.round(n * 10) / 10;

function wrap(artId, inner, opts) {
  opts = opts || {};
  let s = String(inner);
  s = s.replace(/<g id="backdrop"[^>]*>[\s\S]*?<\/g>/g, '');
  // collect ids
  const ids = [];
  s.replace(/\sid="([^"]+)"/g, (m, id) => { ids.push(id); return m; });
  ids.forEach(id => {
    const nid = artId + '-' + id;
    const esc = id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    s = s.replace(new RegExp('id="' + esc + '"', 'g'), 'id="' + nid + '"')
         .replace(new RegExp('url\\(#' + esc + '\\)', 'g'), 'url(#' + nid + ')')
         .replace(new RegExp('href="#' + esc + '"', 'g'), 'href="#' + nid + '"');
  });
  if (/<script|\son[a-z]+=|href="https?:|xlink:href="https?:/i.test(s)) throw new Error(artId + ': forbidden content');
  const label = opts.label ? ' role="img" aria-label="' + String(opts.label).replace(/"/g, '&quot;') + '"' : ' aria-hidden="true"';
  return '<svg viewBox="0 0 400 300" xmlns="http://www.w3.org/2000/svg"' + label + '><g transform="scale(.5)">' + s + '</g></svg>';
}

function writeFile(name, art) {
  const dir = path.join(__dirname, 'out');
  fs.mkdirSync(dir, { recursive: true });
  let out = '/* generated by phase2 generators; do not edit by hand */\n(function(){\nwindow.ART = window.ART || {};\n';
  Object.keys(art).forEach(id => { out += 'ART[' + JSON.stringify(id) + '] = ' + JSON.stringify(art[id]) + ';\n'; });
  out += '})();\n';
  const file = path.join(dir, 'art2-' + name + '.js');
  fs.writeFileSync(file, out);
  const sizes = Object.keys(art).map(id => id + ':' + Math.round(art[id].length / 1024) + 'KB').join(' ');
  console.log('wrote', file, '\n', sizes);
  return file;
}

// deterministic pseudo-random (so regenerating gives identical art)
function rng(seed) { let s = seed >>> 0 || 1; return () => (s = (s * 1664525 + 1013904223) >>> 0) / 4294967296; }

// a leaf-shaped feather pointing +x from the origin; wrap in a transformed <g>.  L length, w half-width, bend tip offset.
function leafFeather(L, w, bend, fill, lite) {
  const p = `M0,0 C${f(L*.22)},${f(-w*1.15)} ${f(L*.72)},${f(-w + bend*.5)} ${f(L)},${f(bend)} C${f(L*.78)},${f(w*.9 + bend*.55)} ${f(L*.26)},${f(w*1.1)} 0,0 Z`;
  let s = `<path d="${p}" fill="${fill}"/>`;
  if (lite) {
    s += `<path d="M${f(L*.06)},0 Q${f(L*.55)},${f(bend*.35)} ${f(L*.96)},${f(bend*.97)}" stroke="${lite}" stroke-width="3" fill="none" stroke-linecap="round" opacity=".7"/>`;
    [0.25, 0.4, 0.55, 0.7, 0.84].forEach(t => {
      const x = L * t, y = bend * t * t * 0.9;
      s += `<path d="M${f(x)},${f(y)} l${f(L*.06)},${f(-w*.55)} M${f(x)},${f(y)} l${f(L*.06)},${f(w*.55)}" stroke="${lite}" stroke-width="2" opacity=".35" fill="none" stroke-linecap="round"/>`;
    });
  }
  return s;
}

// overlapping scale/feather field clipped by you: rows of pointed scales, fill colours per row, drawn bottom row first
function scaleField(x0, y0, cols, rows, dx, dy, size, fills, hi) {
  let s = '';
  for (let r = rows - 1; r >= 0; r--) {
    for (let c = 0; c < cols; c++) {
      const x = x0 + c * dx + (r % 2) * dx / 2, y = y0 + r * dy, h = size;
      s += `<path d="M${f(x-h)},${f(y-h*1.3)} L${f(x+h)},${f(y-h*1.3)} L${f(x+h)},${f(y)} C${f(x+h)},${f(y+h*.9)} ${f(x+h*.4)},${f(y+h*1.4)} ${f(x)},${f(y+h*1.8)} C${f(x-h*.4)},${f(y+h*1.4)} ${f(x-h)},${f(y+h*.9)} ${f(x-h)},${f(y)} Z" fill="${fills[Math.min(r, fills.length-1)]}" stroke="#000" stroke-opacity=".22" stroke-width="2"/>`;
      if (hi) s += `<path d="M${f(x-h*.72)},${f(y+h*.15)} C${f(x-h*.72)},${f(y+h*.8)} ${f(x-h*.3)},${f(y+h*1.2)} ${f(x-h*.05)},${f(y+h*1.45)}" stroke="${hi}" stroke-width="2.5" fill="none" stroke-linecap="round" opacity=".6"/>`;
    }
  }
  return s;
}

module.exports = { wrap, writeFile, rng, f, leafFeather, scaleField };
