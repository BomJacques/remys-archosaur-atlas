"""Import speculative-biology drawings -> assets/art/spec/*.webp + assets/art/spec.js (window.SPEC)."""
import os, sys, json, glob
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(sys.argv[1] if len(sys.argv) > 1 else r'F:\Claude code\drawings')
OUT = os.path.join(ROOT, 'assets', 'art', 'spec')
os.makedirs(OUT, exist_ok=True)


def conv(rel, name, maxw=1100):
    im = Image.open(os.path.join(SRC, rel)).convert('RGBA')
    bb = im.getchannel('A').point(lambda v: 255 if v > 10 else 0).getbbox()
    if bb:
        im = im.crop(bb)
    if im.width > maxw:
        im = im.resize((maxw, round(im.height * maxw / im.width)), Image.LANCZOS)
    p = os.path.join(OUT, name + '.webp')
    im.save(p, 'WEBP', quality=84, method=6)
    return {'src': 'assets/art/spec/%s.webp' % name, 'aspect': round(im.height / im.width, 4)}


spec = {'dinos': [], 'modern': [], 'silly': []}
dinos = [('01', 't-rex', 'tyrannosaurus-rex', 't-rex-feather-mane'), ('02', 'triceratops', 'triceratops', 'triceratops-frill-display'),
         ('03', 'diplodocus', 'diplodocus', 'diplodocus-throat-sail'), ('04', 'quetzalcoatlus', 'quetzalcoatlus', 'quetzalcoatlus-coat-and-display'),
         ('05', 'postosuchus', 'postosuchus', 'postosuchus-neck-ruff'), ('06', 'archaeopteryx', 'archaeopteryx', 'archaeopteryx-fan-display')]
for n, key, ref, sp in dinos:
    spec['dinos'].append({'id': key,
                          'ref': conv('speculative-biology/archosaurs/atlas-reference/%s-%s.png' % (n, ref), 'ref-' + key),
                          'spec': conv('speculative-biology/archosaurs/speculative/%s-%s.png' % (n, sp), 'spec-' + key)})
for key in ('african-elephant', 'barn-owl', 'blue-whale', 'emperor-penguin'):
    spec['modern'].append({'id': key,
                           'bones': conv('speculative-biology/modern/cutouts/%s-shrink-wrapped.png' % key, 'wrap-' + key, 800),
                           'living': conv('speculative-biology/modern/cutouts/%s-living.png' % key, 'live-' + key, 800)})
for f in sorted(glob.glob(os.path.join(SRC, 'speculative-biology-silly', '*.png'))):
    base = os.path.splitext(os.path.basename(f))[0]
    spec['silly'].append(dict(id=base[3:], **conv('speculative-biology-silly/' + os.path.basename(f), 'silly-' + base[3:], 900)))
with open(os.path.join(ROOT, 'assets', 'art', 'spec.js'), 'w', encoding='utf-8') as fh:
    fh.write('/* generated by tools/art/import_spec.py */\nwindow.SPEC = ' + json.dumps(spec, indent=1) + ';\n')
tot = sum(os.path.getsize(p) for p in glob.glob(os.path.join(OUT, '*.webp')))
print('spec images:', len(glob.glob(os.path.join(OUT, '*.webp'))), '%d KB total' % (tot // 1024))
