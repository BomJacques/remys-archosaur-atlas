"""Turn generated illustrations (white background) into site-ready transparent WebP art.

Usage:
    python tools/art/process.py [source_dir] [--tol 18] [--shadow]
Defaults: source_dir = art-source/   (files named <id>.png / .jpg / .webp, e.g. triceratops.png)
Output:   assets/art/<id>.webp  +  assets/art/index.js  (registers every image in window.ART)

What it does per image:
  1. removes the plain white background (flood fill from the border, so white INSIDE the animal is kept)
  2. softens the cut edge and trims white fringe
  3. crops to the animal, fits it on a 4:3 canvas (1000x750) with a margin, optional soft ground shadow
  4. saves a small WebP (target well under 150 KB)
"""
import sys, os, glob, json, argparse
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

W, H = 1000, 750
MARGIN = 0.05


def remove_white(im, tol):
    rgb = np.asarray(im.convert('RGB')).astype(np.int16)
    near_white = (rgb.min(axis=2) >= 255 - tol)
    mask = Image.fromarray((near_white * 255).astype(np.uint8), 'L')
    # pad with a white frame so a single flood fill reaches every border-touching white region
    pad = Image.new('L', (mask.width + 2, mask.height + 2), 255)
    pad.paste(mask, (1, 1))
    ImageDraw.floodfill(pad, (0, 0), 128, thresh=0)
    filled = np.asarray(pad.crop((1, 1, mask.width + 1, mask.height + 1))) == 128
    alpha = np.where(filled, 0, 255).astype(np.uint8)
    a = Image.fromarray(alpha, 'L')
    a = a.filter(ImageFilter.MinFilter(3))           # trim 1px white fringe
    a = a.filter(ImageFilter.GaussianBlur(1.2))      # soft edge
    out = im.convert('RGBA')
    out.putalpha(a)
    return out


def fit_canvas(im, shadow):
    bbox = im.getchannel('A').point(lambda v: 255 if v > 12 else 0).getbbox()
    if not bbox:
        raise ValueError('image is empty after background removal')
    im = im.crop(bbox)
    maxw, maxh = W * (1 - 2 * MARGIN), H * (1 - 2 * MARGIN) - (30 if shadow else 0)
    s = min(maxw / im.width, maxh / im.height)
    im = im.resize((max(1, round(im.width * s)), max(1, round(im.height * s))), Image.LANCZOS)
    canvas = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    x = (W - im.width) // 2
    y = H - round(H * MARGIN) - im.height - (24 if shadow else 0)
    if shadow:
        sh = Image.new('L', (W, H), 0)
        d = ImageDraw.Draw(sh)
        cx, cy = W // 2, y + im.height + 6
        d.ellipse((cx - im.width * 0.42, cy - 12, cx + im.width * 0.42, cy + 14), fill=70)
        sh = sh.filter(ImageFilter.GaussianBlur(9))
        black = Image.new('RGBA', (W, H), (20, 30, 40, 255))
        black.putalpha(sh)
        canvas.alpha_composite(black)
    canvas.alpha_composite(im, (x, y))
    return canvas


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('src', nargs='?', default='art-source')
    ap.add_argument('--tol', type=int, default=18, help='how close to pure white counts as background (0-60)')
    ap.add_argument('--shadow', action='store_true', help='add a soft ground shadow under each animal')
    ap.add_argument('--quality', type=int, default=86)
    a = ap.parse_args()

    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    src = a.src if os.path.isabs(a.src) else os.path.join(root, a.src)
    out_dir = os.path.join(root, 'assets', 'art')
    os.makedirs(out_dir, exist_ok=True)

    files = []
    for ext in ('png', 'jpg', 'jpeg', 'webp'):
        files += glob.glob(os.path.join(src, '*.' + ext))
    if not files:
        print('No images found in', src)
        return 1

    for f in sorted(files):
        aid = os.path.splitext(os.path.basename(f))[0].lower().replace(' ', '-').replace('_', '-')
        try:
            im = Image.open(f)
            im.load()
            if max(im.size) > 1800:
                s = 1800 / max(im.size)
                im = im.resize((round(im.width * s), round(im.height * s)), Image.LANCZOS)
            if im.mode == 'RGBA' and im.getchannel('A').getextrema()[0] < 250:
                cut = im  # already transparent: keep its alpha
            else:
                cut = remove_white(im, a.tol)
            final = fit_canvas(cut, a.shadow)
            dest = os.path.join(out_dir, aid + '.webp')
            final.save(dest, 'WEBP', quality=a.quality, method=6)
            print('%-22s %4d KB' % (aid, os.path.getsize(dest) // 1024))
        except Exception as e:
            print('FAILED', f, e)

    # (re)write the registry from whatever is in assets/art
    ids = sorted(os.path.splitext(os.path.basename(p))[0] for p in glob.glob(os.path.join(out_dir, '*.webp')))
    js = ['/* generated by tools/art/process.py: raster illustrations override the old vector art */',
          '(function(){', 'window.ART = window.ART || {};']
    for i in ids:
        svg = ('<svg viewBox="0 0 400 300" xmlns="http://www.w3.org/2000/svg"><image href="assets/art/%s.webp" '
               'x="0" y="0" width="400" height="300" preserveAspectRatio="xMidYMid meet"/></svg>' % i)
        js.append('ART[%s] = %s;' % (json.dumps(i), json.dumps(svg)))
    js.append('})();')
    with open(os.path.join(out_dir, 'index.js'), 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(js) + '\n')
    print('registered %d images' % len(ids))
    return 0


if __name__ == '__main__':
    sys.exit(main())
