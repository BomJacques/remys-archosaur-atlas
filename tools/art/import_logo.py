"""Use a painted circle as the app logo.  python tools/art/import_logo.py path/to/logo.png
Crops to the circle, makes everything outside it transparent, writes assets/art/logo.webp + logo.js (ART.logo)."""
import os, sys, json
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = sys.argv[1]
im = Image.open(src).convert('RGBA')
A = np.asarray(im.getchannel('A')).astype(int)
if A.min() < 250:   # already transparent outside the circle: trust the alpha channel
    mask = A > 10
else:               # white background: everything that is not near-white
    mask = np.asarray(im.convert('RGB')).astype(int).min(axis=2) < 240
ys, xs = np.where(mask)
x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
side = max(x1 - x0, y1 - y0) + 1
cx, cy = (x0 + x1) // 2, (y0 + y1) // 2
im = im.crop((cx - side // 2, cy - side // 2, cx - side // 2 + side, cy - side // 2 + side)).resize((720, 720), Image.LANCZOS)
m = Image.new('L', (720 * 4, 720 * 4), 0)
ImageDraw.Draw(m).ellipse((6, 6, 720 * 4 - 7, 720 * 4 - 7), fill=255)
m = m.resize((720, 720), Image.LANCZOS)
im.putalpha(m)
out = os.path.join(ROOT, 'assets', 'art', 'logo.webp')
im.save(out, 'WEBP', quality=88, method=6)
png = os.path.join(ROOT, 'assets', 'art', 'logo-192.png')
im.resize((192, 192), Image.LANCZOS).save(png)
svg = '<svg viewBox="0 0 300 300" xmlns="http://www.w3.org/2000/svg"><image href="assets/art/logo.webp" x="0" y="0" width="300" height="300"/></svg>'
open(os.path.join(ROOT, 'assets', 'art', 'logo.js'), 'w', encoding='utf-8').write(
    '/* generated by tools/art/import_logo.py */\n(function(){ window.ART = window.ART || {}; ART["logo"] = %s; })();\n' % json.dumps(svg))
print('logo written', os.path.getsize(out) // 1024, 'KB')
