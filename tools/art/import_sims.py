"""Import comparison / simulation drawings.  python tools/art/import_sims.py [drawings_dir]

* giants-image-replacements/comparison-cutouts/*.png  -> assets/art/compare/<id>.webp
  real-world width comes from comparison-common-scale (100 px = 1 m), saved in assets/art/compare.js
* seed-beaks/*, grow-a-neck/*, island dwarfing -> assets/art/sim/<name>.webp  (window.SIMART)
"""
import os, sys, json, glob
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = sys.argv[1] if len(sys.argv) > 1 else r'F:\Claude code\drawings'
OUT = os.path.join(ROOT, 'assets', 'art')


def trim(im):
    im = im.convert('RGBA')
    bb = im.getchannel('A').point(lambda v: 255 if v > 10 else 0).getbbox()
    return im.crop(bb) if bb else im


def save(im, path, maxw, q=84):
    if im.width > maxw:
        im = im.resize((maxw, round(im.height * maxw / im.width)), Image.LANCZOS)
    im.save(path, 'WEBP', quality=q, method=6)
    return im.size


def main():
    os.makedirs(os.path.join(OUT, 'compare'), exist_ok=True)
    os.makedirs(os.path.join(OUT, 'sim'), exist_ok=True)
    g = os.path.join(SRC, 'giants-image-replacements')
    compare = {}
    for f in sorted(glob.glob(os.path.join(g, 'comparison-cutouts', '*.png'))):
        k = os.path.splitext(os.path.basename(f))[0]
        cs = os.path.join(g, 'comparison-common-scale', k + '.png')
        if not os.path.exists(cs):
            print('no common-scale for', k); continue
        cw, ch = Image.open(cs).size
        im = trim(Image.open(f))
        w, h = save(im, os.path.join(OUT, 'compare', k + '.webp'), 1400)
        compare[k] = {'src': 'assets/art/compare/%s.webp' % k, 'widthM': round(cw / 100.0, 2), 'heightM': round(ch / 100.0, 2), 'aspect': round(h / w, 4)}
        print('%-18s %5.2f m wide %5.2f m tall  %d KB' % (k, cw / 100.0, ch / 100.0, os.path.getsize(os.path.join(OUT, 'compare', k + '.webp')) // 1024))

    sim = {}
    pairs = {
        'beak-thin': 'seed-beaks/bird-thin-beak.png', 'beak-medium': 'seed-beaks/bird-medium-beak.png', 'beak-thick': 'seed-beaks/bird-thick-beak.png',
        'seed-hard': 'seed-beaks/seed-hard.png', 'seeds-soft': 'seed-beaks/seeds-soft.png',
        'neck-short': 'grow-a-neck/diplodocus-short-neck.png', 'neck-medium': 'grow-a-neck/diplodocus-medium-neck.png', 'neck-long': 'grow-a-neck/diplodocus-long-neck.png',
        'tree-none': 'grow-a-neck/tree-no-high-leaves.png', 'tree-some': 'grow-a-neck/tree-some-high-leaves.png', 'tree-lots': 'grow-a-neck/tree-lots-of-high-leaves.png',
        'island-sauropod': 'giants-image-replacements/exercise-cutouts/island-dwarfing-sauropod.png', 'fern': 'giants-image-replacements/exercise-cutouts/fern.png',
    }
    for k, rel in pairs.items():
        f = os.path.join(SRC, rel)
        if not os.path.exists(f):
            print('missing', rel); continue
        im = trim(Image.open(f))
        w, h = save(im, os.path.join(OUT, 'sim', k + '.webp'), 700)
        sim[k] = {'src': 'assets/art/sim/%s.webp' % k, 'aspect': round(h / w, 4)}
        print('sim %-16s %d KB' % (k, os.path.getsize(os.path.join(OUT, 'sim', k + '.webp')) // 1024))

    with open(os.path.join(OUT, 'compare.js'), 'w', encoding='utf-8') as fh:
        fh.write('/* generated by tools/art/import_sims.py */\nwindow.COMPARE = %s;\nwindow.SIMART = %s;\n' % (json.dumps(compare, indent=1), json.dumps(sim, indent=1)))
    print('done: %d comparison images, %d sim images' % (len(compare), len(sim)))


if __name__ == '__main__':
    main()
