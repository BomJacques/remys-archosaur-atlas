"""Import painted family figures: python tools/art/import_family.py [folder]
Expects <folder>/<name>.png for: grandma grandpa granny pop mum dad aunt sister cousin (transparent or white background).
Writes assets/art/family/<name>.webp and assets/art/family.js (window.FAMILY)."""
import os, sys, json, glob
from PIL import Image
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import importlib.util
spec = importlib.util.spec_from_file_location('proc', os.path.join(os.path.dirname(os.path.abspath(__file__)), 'process.py'))
proc = importlib.util.module_from_spec(spec); spec.loader.exec_module(proc)
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = sys.argv[1] if len(sys.argv) > 1 else r'F:\Claude code\drawings\family'
OUT = os.path.join(ROOT, 'assets', 'art', 'family'); os.makedirs(OUT, exist_ok=True)
fam = {}
for f in sorted(glob.glob(os.path.join(SRC, '*.png')) + glob.glob(os.path.join(SRC, '*.jpg'))):
    k = os.path.splitext(os.path.basename(f))[0].lower()
    im = Image.open(f); im.load()
    cut = im if (im.mode == 'RGBA' and im.getchannel('A').getextrema()[0] < 250) else proc.remove_white(im, 18)
    bb = cut.getchannel('A').point(lambda v: 255 if v > 10 else 0).getbbox(); cut = cut.crop(bb)
    if cut.height > 700: cut = cut.resize((round(cut.width * 700 / cut.height), 700), Image.LANCZOS)
    cut.save(os.path.join(OUT, k + '.webp'), 'WEBP', quality=86, method=6)
    fam[k] = {'src': 'assets/art/family/%s.webp' % k, 'aspect': round(cut.height / cut.width, 4)}
    print(k, os.path.getsize(os.path.join(OUT, k + '.webp')) // 1024, 'KB')
open(os.path.join(ROOT, 'assets', 'art', 'family.js'), 'w', encoding='utf-8').write('/* generated by tools/art/import_family.py */\nwindow.FAMILY = ' + json.dumps(fam, indent=1) + ';\n')
print('family figures:', len(fam))
