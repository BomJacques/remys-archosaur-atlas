"""Import the painted family portraits.  python tools/art/import_family_portraits.py [folder]
Writes assets/art/family/<key>.webp and assets/art/family.js (window.FAMILY)."""
import os, sys, json
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = sys.argv[1] if len(sys.argv) > 1 else r'F:\Claude code\drawings\atlas-family-portraits'
OUT = os.path.join(ROOT, 'assets', 'art', 'family')
os.makedirs(OUT, exist_ok=True)
MAP = {
    '01-mother': 'mum', '02-father': 'dad', '03-kid-1': 'you', '04-kid-2': 'sibling', '05-cousin': 'cousin',
    '06-maternal-grandmother': 'gm1', '07-maternal-grandfather': 'gf1', '08-paternal-grandmother': 'gm2', '09-paternal-grandfather': 'gf2',
    '10-maternal-great-grandmother-1': 'ggm1', '11-maternal-great-grandfather-1': 'ggf1', '12-maternal-great-grandmother-2': 'ggm2', '13-maternal-great-grandfather-2': 'ggf2',
    '14-paternal-great-grandmother-1': 'ggm3', '15-paternal-great-grandfather-1': 'ggf3', '16-paternal-great-grandmother-2': 'ggm4', '17-paternal-great-grandfather-2': 'ggf4',
}
fam = {}
for stem, key in MAP.items():
    f = os.path.join(SRC, stem + '.png')
    if not os.path.exists(f):
        print('MISSING', f); continue
    im = Image.open(f).convert('RGBA')
    bb = im.getchannel('A').point(lambda v: 255 if v > 10 else 0).getbbox()
    im = im.crop(bb)
    if im.width > 340:
        im = im.resize((340, round(im.height * 340 / im.width)), Image.LANCZOS)
    p = os.path.join(OUT, key + '.webp')
    im.save(p, 'WEBP', quality=86, method=6)
    fam[key] = {'src': 'assets/art/family/%s.webp' % key, 'aspect': round(im.height / im.width, 4)}
    print('%-8s %3d KB' % (key, os.path.getsize(p) // 1024))

# optional extra: a photo (or painting) of an aunt or uncle, saved as aunt-uncle.png/.jpg in the portraits folder
for ext in ('png', 'jpg', 'jpeg', 'webp'):
    f = os.path.join(SRC, 'aunt-uncle.' + ext)
    if os.path.exists(f):
        im = Image.open(f).convert('RGBA')
        w, h = im.size
        side = min(w, h)
        # centre crop to a square; pass a different focus with:  FACE_X / FACE_Y (0-1) environment variables
        fx = float(os.environ.get('FACE_X', '0.5')); fy = float(os.environ.get('FACE_Y', '0.5'))
        x0 = int(max(0, min(w - side, fx * w - side / 2))); y0 = int(max(0, min(h - side, fy * h - side / 2)))
        im = im.crop((x0, y0, x0 + side, y0 + side)).resize((340, 340), Image.LANCZOS)
        p2 = os.path.join(OUT, 'aunt.webp'); im.save(p2, 'WEBP', quality=88, method=6)
        fam['aunt'] = {'src': 'assets/art/family/aunt.webp', 'aspect': 1.0}
        print('aunt/uncle imported from', os.path.basename(f))
        break
with open(os.path.join(ROOT, 'assets', 'art', 'family.js'), 'w', encoding='utf-8') as fh:
    fh.write('/* generated by tools/art/import_family_portraits.py */\nwindow.FAMILY = ' + json.dumps(fam, indent=1) + ';\n')
print('family portraits:', len(fam))
